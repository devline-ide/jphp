package php.runtime.reflection.helper;

import php.runtime.Memory;
import php.runtime.env.Context;
import php.runtime.env.Environment;
import php.runtime.exceptions.CriticalException;
import php.runtime.lang.Closure;
import php.runtime.memory.ObjectMemory;
import php.runtime.reflection.ClassEntity;
import php.runtime.reflection.ParameterEntity;

import java.lang.reflect.InvocationTargetException;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.HexFormat;
import java.util.List;
import java.util.Objects;

public class ClosureEntity extends ClassEntity {
    protected boolean returnReference;
    public ParameterEntity[] parameters;
    public ParameterEntity[] uses;

    protected ObjectMemory singleton;
    protected GeneratorEntity generatorEntity;
    private CapturePlan ownershipCapturePlan;

    public enum CaptureMode { VALUE, CELL }
    public enum CapturePlanOrigin { SOURCE_AST, VALIDATED_DUMP }
    public record CaptureEntry(String name, CaptureMode mode) {
        public CaptureEntry {
            if (name == null || name.isEmpty() || name.indexOf('\0') >= 0)
                throw new IllegalArgumentException("Invalid closure capture name");
            Objects.requireNonNull(mode, "capture mode");
        }
    }

    /** Immutable capture ordering only; does not certify constructors, bodies or an ownership domain. */
    public static final class CapturePlan {
        private final String generatedClassName, bytecodeSha256;
        private final boolean staticClosure, usesThis;
        private final List<CaptureEntry> entries;
        private final CapturePlanOrigin origin;
        private final boolean emptyShellConstructorVerified;

        private CapturePlan(String generatedClassName, String bytecodeSha256, boolean staticClosure,
                            boolean usesThis, List<CaptureEntry> entries, CapturePlanOrigin origin, boolean emptyShellConstructorVerified) {
            this.generatedClassName = Objects.requireNonNull(generatedClassName);
            this.bytecodeSha256 = Objects.requireNonNull(bytecodeSha256);
            this.staticClosure = staticClosure; this.usesThis = usesThis;
            this.entries = List.copyOf(entries); this.origin = origin;
            this.emptyShellConstructorVerified = emptyShellConstructorVerified;
            HashSet<String> names = new HashSet<>();
            for (CaptureEntry entry : this.entries)
                if (!names.add(entry.name())) throw new IllegalArgumentException("Duplicate closure capture name");
        }
        public String generatedClassName() { return generatedClassName; }
        public String bytecodeSha256() { return bytecodeSha256; }
        public boolean staticClosure() { return staticClosure; }
        public boolean usesThis() { return usesThis; }
        public List<CaptureEntry> entries() { return entries; }
        public CapturePlanOrigin origin() { return origin; }
        public boolean emptyShellConstructorVerified() { return emptyShellConstructorVerified; }
    }

    private String captureBytecodeHash() {
        if (getData() == null || getData().length == 0)
            throw new IllegalArgumentException("Closure capture plan requires generated bytecode");
        try { return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(getData())); }
        catch (NoSuchAlgorithmException impossible) { throw new IllegalStateException(impossible); }
    }

    private void validateCapturePlan(CapturePlan plan) {
        if (!Objects.equals(plan.generatedClassName(), getInternalName())
                || !plan.bytecodeSha256().equals(captureBytecodeHash()))
            throw new IllegalArgumentException("Closure capture plan bytecode identity mismatch");
        if (uses == null || uses.length != plan.entries().size())
            throw new IllegalArgumentException("Closure capture plan count mismatch");
        for (int i = 0; i < uses.length; i++) {
            CaptureEntry entry = plan.entries().get(i);
            if (uses[i] == null || !entry.name().equals(uses[i].getName())
                    || (entry.mode() == CaptureMode.CELL) != uses[i].isReference())
                throw new IllegalArgumentException("Closure capture plan metadata mismatch");
        }
    }

    public CapturePlan getOwnershipCapturePlan() {
        if (ownershipCapturePlan != null) validateCapturePlan(ownershipCapturePlan);
        return ownershipCapturePlan;
    }

    /** Called after AST capture metadata and generated bytecode are complete. */
    public void recordSourceCapturePlan(boolean staticClosure, boolean usesThis) {
        if (ownershipCapturePlan != null) throw new IllegalStateException("Closure capture plan already recorded");
        if (uses == null) throw new IllegalArgumentException("Closure AST capture metadata is missing");
        ArrayList<CaptureEntry> entries = new ArrayList<>();
        for (ParameterEntity use : uses)
            entries.add(new CaptureEntry(use.getName(), use.isReference() ? CaptureMode.CELL : CaptureMode.VALUE));
        CapturePlan plan = new CapturePlan(getInternalName(), captureBytecodeHash(), staticClosure,
                usesThis, entries, CapturePlanOrigin.SOURCE_AST, PhpClosureShellVerifier.verify(getData(), getInternalName()));
        validateCapturePlan(plan); ownershipCapturePlan = plan;
    }

    /** Validated wire metadata preserves declaration order; it is not an arbitrary Java constructor capability. */
    public void recordDumpCapturePlan(String generatedClassName, String bytecodeSha256,
            boolean staticClosure, boolean usesThis, List<CaptureEntry> entries) {
        if (ownershipCapturePlan != null) throw new IllegalStateException("Closure capture plan already recorded");
        CapturePlan plan = new CapturePlan(generatedClassName, bytecodeSha256, staticClosure,
                usesThis, entries, CapturePlanOrigin.VALIDATED_DUMP, PhpClosureShellVerifier.verify(getData(), getInternalName()));
        validateCapturePlan(plan); ownershipCapturePlan = plan;
    }

    public ClosureEntity(Context context) {
        super(context);
        setName(Closure.class.getSimpleName());
        setType(Type.CLOSURE);
    }

    public boolean isReturnReference() {
        return returnReference;
    }

    @Override
    public boolean isHiddenInCallStack() {
        return true;
    }

    public void setReturnReference(boolean returnReference) {
        this.returnReference = returnReference;
    }

    public void setParameters(ParameterEntity[] parameters) {
        this.parameters = parameters;
    }

    public void setUses(ParameterEntity[] uses) {
        this.uses = uses;
    }

    /**
     * Use getSingleton(string)
     */
    @Deprecated
    public ObjectMemory getSingleton() {
        return getSingleton(null);
    }

    public ObjectMemory getSingleton(String selfContextClass) {
        if (singleton != null) {
            return singleton;
        }

        synchronized (this) {
            if (singleton == null) {
                try {
                    singleton = new ObjectMemory((Closure) this.nativeConstructor.newInstance(null, this, Memory.NULL, selfContextClass, null));
                } catch (InstantiationException | IllegalAccessException e) {
                    throw new CriticalException(e);
                } catch (InvocationTargetException e) {
                    throw new CriticalException(e.getTargetException());
                }
            }
        }

        return singleton;
    }

    @Override
    public String getName() {
        return parent.getName();
    }

    @Override
    public String getLowerName() {
        return parent == null ? super.getLowerName() : parent.getLowerName();
    }

    @Override
    public boolean equals(Object o) {
        return o instanceof ClosureEntity;
    }

    @Override
    public void setNativeClazz(Class<?> nativeClazz) {
        this.nativeClazz = nativeClazz;
        if (!nativeClazz.isInterface()){
            try {
                this.nativeConstructor = nativeClazz.getConstructor(Environment.class, ClassEntity.class, Memory.class, String.class, Memory[].class);
                this.nativeConstructor.setAccessible(true);

            } catch (NoSuchMethodException e) {
                throw new CriticalException(e);
            }
        }
    }

    public GeneratorEntity getGeneratorEntity() {
        return generatorEntity;
    }

    public void setGeneratorEntity(GeneratorEntity generatorEntity) {
        this.generatorEntity = generatorEntity;
    }
}
